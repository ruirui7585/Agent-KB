#!/usr/bin/env node
/**
 * Laka PM 收件箱扫描与离线看板数据同步脚本（零外部依赖，仅使用 Node 标准库）
 *
 * 用法（在 Projects/laka 目录下，或从任意路径调用本脚本）：
 *   node pm-inbox/scripts/scan-inbox.mjs scan   # 扫描 raw/ 截图与 quick-notes.md，计算指纹并查重
 *   node pm-inbox/scripts/scan-inbox.mjs sync   # 将 library-data.json 同步编译为离线可读的 library-data.js
 */

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const LAKA_ROOT = path.resolve(__dirname, '../..');
const RAW_DIR = path.join(LAKA_ROOT, 'pm-inbox/raw');
const NOTES_FILE = path.join(LAKA_ROOT, 'pm-inbox/quick-notes.md');
const DATA_DIR = path.join(LAKA_ROOT, 'agents/competitor-analysis');
const DATA_JSON = path.join(DATA_DIR, 'library-data.json');
const DATA_JS = path.join(DATA_DIR, 'library-data.js');

const IMAGE_EXTS = new Set(['.png', '.jpg', '.jpeg', '.webp', '.gif']);

function toPosixRelative(absPath) {
  return path.relative(LAKA_ROOT, absPath).split(path.sep).join('/');
}

function sha256File(filePath) {
  const hash = crypto.createHash('sha256');
  hash.update(fs.readFileSync(filePath));
  return hash.digest('hex');
}

function loadLibrary() {
  if (!fs.existsSync(DATA_JSON)) {
    throw new Error(`找不到索引文件：${toPosixRelative(DATA_JSON)}`);
  }
  return JSON.parse(fs.readFileSync(DATA_JSON, 'utf8'));
}

function parseQuickNotes() {
  if (!fs.existsSync(NOTES_FILE)) return [];
  const raw = fs.readFileSync(NOTES_FILE, 'utf8');
  const sepIndex = raw.indexOf('---');
  if (sepIndex === -1) return [];
  const body = raw
    .slice(sepIndex + 3)
    .replace(/<!--[\s\S]*?-->/g, '')
    .split(/\r?\n/)
    .map((line) => line.replace(/^\s*[-*]\s*/, '').trim())
    .filter(Boolean);
  return body;
}

function runScan() {
  const library = loadLibrary();
  const knownHashes = new Map();
  for (const card of library.cards || []) {
    if (card.contentHash) {
      knownHashes.set(card.contentHash, {
        id: card.id,
        competitor: card.competitor,
        module: card.module,
        title: card.title,
        imagePath: card.imagePath,
      });
    }
  }

  const newImages = [];
  const duplicateImages = [];

  if (fs.existsSync(RAW_DIR)) {
    const entries = fs.readdirSync(RAW_DIR, { withFileTypes: true });
    for (const entry of entries) {
      if (!entry.isFile() || entry.name.startsWith('.')) continue;
      const ext = path.extname(entry.name).toLowerCase();
      if (!IMAGE_EXTS.has(ext)) continue;

      const absPath = path.join(RAW_DIR, entry.name);
      const stat = fs.statSync(absPath);
      const hash = sha256File(absPath);
      const item = {
        fileName: entry.name,
        relativePath: toPosixRelative(absPath),
        sizeBytes: stat.size,
        modifiedAt: stat.mtime.toISOString(),
        sha256: hash,
      };

      if (knownHashes.has(hash)) {
        duplicateImages.push({ ...item, existingCard: knownHashes.get(hash) });
      } else {
        newImages.push(item);
      }
    }
  }

  const pendingNotes = parseQuickNotes();

  const report = {
    scannedAt: new Date().toISOString(),
    summary: {
      newImageCount: newImages.length,
      duplicateImageCount: duplicateImages.length,
      pendingNoteCount: pendingNotes.length,
      totalIndexedCards: (library.cards || []).length,
      totalCopyItems: (library.copyItems || []).length,
      totalMemos: (library.memos || []).length,
    },
    newImages,
    duplicateImages,
    pendingNotes,
  };

  console.log(JSON.stringify(report, null, 2));
}

function runSync() {
  const library = loadLibrary();
  library.updatedAt = new Date().toISOString();
  fs.writeFileSync(DATA_JSON, `${JSON.stringify(library, null, 2)}\n`, 'utf8');

  const banner = [
    '// Auto-generated by pm-inbox/scripts/scan-inbox.mjs sync',
    '// 用于支持本地双击直接离线打开 hub.html（无需启动本地服务器）',
    `window.LAKA_PM_LIBRARY = ${JSON.stringify(library, null, 2)};`,
    '',
  ].join('\n');

  fs.writeFileSync(DATA_JS, banner, 'utf8');
  console.log(
    `[OK] 已同步离线数据：${toPosixRelative(DATA_JS)}（能力卡片 ${(library.cards || []).length} 条 / 文案 ${(library.copyItems || []).length} 条 / 备忘 ${(library.memos || []).length} 条）`
  );
}

const cmd = process.argv[2] || 'scan';
if (cmd === 'scan') {
  runScan();
} else if (cmd === 'sync') {
  runSync();
} else {
  console.error('用法：node pm-inbox/scripts/scan-inbox.mjs [scan|sync]');
  process.exit(1);
}
